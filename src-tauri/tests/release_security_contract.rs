use serde_json::Value;
use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

fn manifest_path(relative: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join(relative)
}

fn read_json(relative: &str) -> Value {
    serde_json::from_slice(&fs::read(manifest_path(relative)).unwrap()).unwrap()
}

#[test]
fn default_capability_is_scoped_to_registered_commands() {
    let capability = read_json("capabilities/default.json");
    let permissions = capability["permissions"].as_array().unwrap();
    let event_permissions = ["core:event:allow-listen", "core:event:allow-unlisten"]
        .into_iter()
        .collect::<BTreeSet<_>>();
    let app_permissions = permissions
        .iter()
        .map(|permission| permission.as_str().unwrap())
        .filter(|permission| !event_permissions.contains(permission))
        .collect::<BTreeSet<_>>();

    assert_eq!(app_permissions.len(), 37);
    assert_eq!(
        permissions
            .iter()
            .filter_map(Value::as_str)
            .filter(|permission| permission.starts_with("core:event:"))
            .collect::<BTreeSet<_>>(),
        event_permissions
    );

    let source = fs::read_to_string(manifest_path("src/lib.rs")).unwrap();
    let handler = source
        .split_once(".invoke_handler(tauri::generate_handler![")
        .unwrap()
        .1
        .split_once("])")
        .unwrap()
        .0;
    let registered = handler
        .split(|character: char| character == ',' || character == '\n')
        .map(str::trim)
        .filter(|entry| !entry.is_empty())
        .map(|entry| entry.rsplit("::").next().unwrap().to_owned())
        .collect::<BTreeSet<_>>();
    let permitted = app_permissions
        .iter()
        .map(|permission| {
            let command = permission
                .strip_prefix("allow-")
                .expect("app capabilities must use per-command allow permissions")
                .replace('-', "_");
            let definition = fs::read_to_string(manifest_path(&format!(
                "permissions/autogenerated/{command}.toml"
            )))
            .unwrap_or_else(|error| panic!("missing explicit permission for {command}: {error}"));
            let allow_lines = definition
                .lines()
                .filter(|line| line.trim_start().starts_with("commands.allow ="))
                .map(|line| line.trim().to_owned())
                .collect::<Vec<_>>();
            assert_eq!(
                allow_lines,
                vec![format!("commands.allow = [\"{command}\"]")],
                "{command} permission must allow exactly its matching command"
            );
            assert!(
                !definition.contains("commands.allow = [\"*\"]"),
                "{command} permission must not grant wildcard command access"
            );
            command
        })
        .collect::<BTreeSet<_>>();

    assert_eq!(permitted, registered);
}

#[test]
fn content_security_policy_keeps_production_and_development_origins_bounded() {
    let config = read_json("tauri.conf.json");
    let security = &config["app"]["security"];
    let production = security["csp"].as_str().unwrap();
    let development = security["devCsp"].as_str().unwrap();

    assert!(production.contains("default-src 'self'"));
    assert!(production.contains("connect-src ipc: http://ipc.localhost"));
    assert!(!production.contains("*"));
    assert!(!production.contains("unsafe-eval"));
    assert!(!production.contains("https://"));

    assert!(development.contains("http://127.0.0.1:1420"));
    assert!(development.contains("ws://127.0.0.1:1420"));
    assert!(!development.contains("*"));
    assert!(!development.contains("unsafe-eval"));
    assert!(!development.contains("https://"));
}

#[test]
fn frontend_does_not_depend_on_the_unrestricted_shell_plugin() {
    let package = read_json("../package.json");
    for section in ["dependencies", "devDependencies"] {
        assert!(package[section]["@tauri-apps/plugin-shell"].is_null());
    }

    let frontend = manifest_path("../src");
    let mut pending = vec![frontend];
    while let Some(path) = pending.pop() {
        for entry in fs::read_dir(path).unwrap() {
            let entry = entry.unwrap();
            let path = entry.path();
            if path.is_dir() {
                pending.push(path);
            } else if matches!(
                path.extension().and_then(|extension| extension.to_str()),
                Some("ts" | "tsx")
            ) {
                let source = fs::read_to_string(&path).unwrap();
                assert!(
                    !source.contains("@tauri-apps/plugin-shell"),
                    "frontend shell access is not permitted: {}",
                    path.display()
                );
            }
        }
    }
}

